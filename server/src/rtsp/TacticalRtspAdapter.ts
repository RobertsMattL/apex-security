import { spawn, type ChildProcess } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Config } from '../config.js';
import { logger } from '../util/log.js';
import type { Secrets } from '../util/secrets.js';

const log = logger('rtsp');

export interface PathSource {
  /** Full source URL including credentials. Only ever sent to MediaMTX over localhost. */
  source: string;
  rtspTransport: 'automatic' | 'tcp' | 'udp';
}

export interface PathState {
  name: string;
  ready: boolean;
  readyTime: string | null;
  tracks: string[];
  readers: number;
}

export interface MediaMtxAuthRequest {
  user?: string;
  password?: string;
  token?: string;
  ip?: string;
  action?: string;
  path?: string;
  protocol?: string;
  query?: string;
}

/** Path name used for a camera inside MediaMTX. */
export const cameraPath = (cameraId: string) => `cam_${cameraId}`;

/**
 * Integration with tacticalRtsp's streaming layer: MediaMTX.
 *
 * tacticalRtsp uses MediaMTX for capture, fan-out and re-publishing (pi/mediamtx.yml).
 * Here the server runs its own MediaMTX instance and drives it through the MediaMTX
 * control API: every camera becomes a path `cam_<id>` that pulls the camera's RTSP
 * stream (MediaMTX reconnects automatically when a camera drops), and every consumer
 * (Android player, detector sidecar, snapshot grabs) reads from MediaMTX rather than
 * the camera, so a camera only ever sees one connection.
 *
 * Reader authentication is delegated back to this server (authMethod: http), so camera
 * credentials stay server-side and clients only ever hold short-lived stream tokens.
 */
export class TacticalRtspAdapter {
  private proc?: ChildProcess;
  private stopping = false;
  private restartDelay = 1000;
  private readyListeners: Array<() => void> = [];
  private apiBase: string;

  constructor(
    private config: Config,
    private secrets: Secrets,
    private authorizeReader: (cameraId: string, token: string) => Promise<boolean>,
  ) {
    this.apiBase = `http://127.0.0.1:${config.mediamtx.apiPort}`;
  }

  /** Called whenever MediaMTX (re)starts with an empty path table and needs paths re-applied. */
  onReady(fn: () => void) {
    this.readyListeners.push(fn);
  }

  async start() {
    if (!this.config.mediamtx.manage) {
      await this.waitForApi(15000);
      this.readyListeners.forEach((fn) => fn());
      return;
    }
    const configPath = join(this.config.dataDir, 'mediamtx.yml');
    writeFileSync(configPath, this.renderConfig());
    this.spawn(configPath);
    await this.waitForApi(15000);
  }

  private spawn(configPath: string) {
    log.info(`starting ${this.config.mediamtx.bin} (rtsp :${this.config.mediamtx.rtspPort})`);
    const proc = spawn(this.config.mediamtx.bin, [configPath], { stdio: ['ignore', 'pipe', 'pipe'] });
    this.proc = proc;
    const relay = (buf: Buffer) => {
      for (const line of buf.toString().split('\n')) {
        // MediaMTX logs every reader connect/disconnect at INF; keep WAR/ERR and source state.
        if (/WAR|ERR|ready|not ready|source/.test(line) && line.trim()) log.info(line.trim().replace(/^\S+ \S+ /, ''));
      }
    };
    proc.stdout!.on('data', relay);
    proc.stderr!.on('data', relay);
    proc.on('exit', (code, signal) => {
      if (this.stopping) return;
      log.warn(`mediamtx exited (${code ?? signal}); restarting in ${this.restartDelay}ms`);
      setTimeout(async () => {
        this.spawn(configPath);
        try {
          await this.waitForApi(15000);
        } catch (e) {
          log.error('mediamtx did not come back', e);
        }
      }, this.restartDelay);
      this.restartDelay = Math.min(this.restartDelay * 2, 30000);
    });
  }

  async stop() {
    this.stopping = true;
    const p = this.proc;
    if (!p || p.exitCode !== null) return;
    await new Promise<void>((res) => {
      p.once('exit', () => res());
      p.kill('SIGTERM');
      setTimeout(() => p.kill('SIGKILL'), 3000).unref();
    });
  }

  private renderConfig(): string {
    const { rtspPort, apiPort } = this.config.mediamtx;
    const authUrl = `http://127.0.0.1:${this.config.port}/internal/mediamtx/auth`;
    // No `paths:` beyond what the API adds: requests for unknown paths are rejected.
    return `# Generated by apex-security server. Do not edit; regenerated on every start.
logLevel: info
logDestinations: [stdout]
readTimeout: 10s
writeTimeout: 10s

authMethod: http
authHTTPAddress: ${authUrl}
authHTTPExclude:
  - action: api
  - action: metrics
  - action: pprof

api: yes
apiAddress: 127.0.0.1:${apiPort}

rtsp: yes
rtspAddress: :${rtspPort}
rtspTransports: [udp, tcp]
rtpAddress: :${this.config.mediamtx.rtpPort}
rtcpAddress: :${this.config.mediamtx.rtpPort + 1}

rtmp: no
hls: no
webrtc: no
srt: no
moq: no
playback: no
metrics: no
pprof: no

pathDefaults:
  sourceOnDemand: no

paths: {}
`;
  }

  private async waitForApi(timeoutMs: number) {
    const deadline = Date.now() + timeoutMs;
    for (;;) {
      try {
        const r = await fetch(`${this.apiBase}/v3/config/global/get`);
        if (r.ok) break;
      } catch {
        /* not up yet */
      }
      if (Date.now() > deadline) throw new Error(`MediaMTX API not reachable at ${this.apiBase}`);
      await new Promise((r) => setTimeout(r, 200));
    }
    this.restartDelay = 1000;
    log.info('mediamtx api ready');
    this.readyListeners.forEach((fn) => fn());
  }

  private async api(method: string, path: string, body?: unknown) {
    const r = await fetch(`${this.apiBase}${path}`, {
      method,
      headers: body ? { 'Content-Type': 'application/json' } : undefined,
      body: body ? JSON.stringify(body) : undefined,
    });
    return r;
  }

  async setPath(name: string, src: PathSource) {
    const conf = { source: src.source, rtspTransport: src.rtspTransport, sourceOnDemand: false };
    let r = await this.api('POST', `/v3/config/paths/add/${name}`, conf);
    if (r.status === 400) r = await this.api('POST', `/v3/config/paths/replace/${name}`, conf);
    if (!r.ok) throw new Error(`MediaMTX rejected path ${name}: ${r.status} ${await r.text()}`);
  }

  async removePath(name: string) {
    const r = await this.api('DELETE', `/v3/config/paths/delete/${name}`);
    if (!r.ok && r.status !== 404) throw new Error(`MediaMTX path delete ${name}: ${r.status}`);
  }

  async listPaths(): Promise<Map<string, PathState>> {
    const out = new Map<string, PathState>();
    const r = await this.api('GET', '/v3/paths/list?itemsPerPage=1000');
    if (!r.ok) throw new Error(`MediaMTX paths list: ${r.status}`);
    const body = (await r.json()) as { items: Array<{ name: string; ready: boolean; readyTime: string | null; tracks?: string[]; readers?: unknown[] }> };
    for (const p of body.items ?? []) {
      out.set(p.name, { name: p.name, ready: p.ready, readyTime: p.readyTime, tracks: p.tracks ?? [], readers: p.readers?.length ?? 0 });
    }
    return out;
  }

  /** URL the server's own readers (detector, snapshots) use. */
  internalReadUrl(cameraId: string) {
    const u = encodeURIComponent;
    return `rtsp://${u(this.secrets.internalRtspUser)}:${u(this.secrets.internalRtspPass)}@127.0.0.1:${this.config.mediamtx.rtspPort}/${cameraPath(cameraId)}`;
  }

  /** URL handed to a client; the stream token is the RTSP password. */
  clientReadUrl(cameraId: string, host: string, token: string) {
    return `rtsp://stream:${encodeURIComponent(token)}@${host}:${this.config.mediamtx.rtspPort}/${cameraPath(cameraId)}`;
  }

  /** Decide a MediaMTX auth callback. Only reads of camera paths are ever allowed. */
  async authorize(req: MediaMtxAuthRequest): Promise<boolean> {
    log.debug('auth request', { ...req, password: req.password ? `<${req.password.length} chars>` : '', token: req.token ? `<${req.token.length} chars>` : '' });
    if (req.action !== 'read') return false;
    const m = /^cam_(.+)$/.exec(req.path ?? '');
    if (!m) return false;
    const isLocal = req.ip === '127.0.0.1' || req.ip === '::1';
    if (isLocal && req.user === this.secrets.internalRtspUser && req.password === this.secrets.internalRtspPass) return true;
    const token = req.password || req.token || new URLSearchParams(req.query ?? '').get('token') || '';
    return token ? this.authorizeReader(m[1], token) : false;
  }
}
